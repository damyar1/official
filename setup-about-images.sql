-- اجرای یک‌باره در Supabase > SQL Editor
-- جدول تصاویر مستقل است و متن/تنظیمات فعلی about_settings را تغییر نمی‌دهد.
CREATE TABLE IF NOT EXISTS public.about_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url TEXT NOT NULL,
    title TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.about_images ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "about images public read" ON public.about_images;
CREATE POLICY "about images public read"
ON public.about_images
FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "about images authenticated manage" ON public.about_images;
CREATE POLICY "about images authenticated manage"
ON public.about_images
FOR ALL
TO authenticated
USING (auth.uid() IS NOT NULL)
WITH CHECK (auth.uid() IS NOT NULL);

GRANT SELECT ON public.about_images TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.about_images TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.about_images_id_seq TO authenticated;

NOTIFY pgrst, 'reload schema';
