-- دامیار: کامنت با تأیید مدیر، لایک/دیس‌لایک و کتابخانه علوم دامی
-- پیش‌نیاز: جدول public.posts با ستون id از نوع BIGINT

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 60),
  content text not null check (char_length(trim(content)) between 2 and 2000),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists post_comments_post_status_idx on public.post_comments(post_id, approved, created_at desc);

create table if not exists public.post_reactions (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  visitor_id text not null,
  reaction text not null check (reaction in ('like','dislike')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(post_id, visitor_id)
);
create index if not exists post_reactions_post_idx on public.post_reactions(post_id);

create table if not exists public.library_files (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  file_name text not null,
  file_path text not null unique,
  public_url text not null,
  created_at timestamptz not null default now()
);

alter table public.post_comments enable row level security;
alter table public.post_reactions enable row level security;
alter table public.library_files enable row level security;

-- کاربران فقط کامنت‌های تأییدشده را می‌بینند؛ ارسال کامنت با وضعیت در انتظار است.
drop policy if exists "comments public read approved" on public.post_comments;
create policy "comments public read approved" on public.post_comments for select to anon, authenticated using (approved = true);
drop policy if exists "comments public submit pending" on public.post_comments;
create policy "comments public submit pending" on public.post_comments for insert to anon, authenticated with check (approved = false);
-- ادمین واردشده می‌تواند همه کامنت‌ها را مدیریت کند. در پروژه‌ای که فقط حساب مدیر دارد، همین حساب استفاده شود.
drop policy if exists "comments admin manage" on public.post_comments;
create policy "comments admin manage" on public.post_comments for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists "reactions public read" on public.post_reactions;
create policy "reactions public read" on public.post_reactions for select to anon, authenticated using (true);
drop policy if exists "reactions public insert" on public.post_reactions;
create policy "reactions public insert" on public.post_reactions for insert to anon, authenticated with check (true);
drop policy if exists "reactions public update" on public.post_reactions;
create policy "reactions public update" on public.post_reactions for update to anon, authenticated using (true) with check (reaction in ('like','dislike'));

-- فهرست فایل‌های کتابخانه عمومی است؛ تغییرات فقط برای کاربران واردشده مجاز است.
drop policy if exists "library public read" on public.library_files;
create policy "library public read" on public.library_files for select to anon, authenticated using (true);
drop policy if exists "library admin manage" on public.library_files;
create policy "library admin manage" on public.library_files for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

grant select, insert on public.post_comments to anon, authenticated;
grant select, insert, update on public.post_reactions to anon, authenticated;
grant select on public.library_files to anon, authenticated;
grant insert, update, delete on public.library_files to authenticated;
grant usage, select on sequence public.post_comments_id_seq to anon, authenticated;
grant usage, select on sequence public.post_reactions_id_seq to anon, authenticated;

