-- دامیار: جدول دیدگاه‌ها و واکنش‌های لایک/دیس‌لایک
-- این فایل را یک‌بار در Supabase > SQL Editor اجرا کنید.

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 60),
  content text not null check (char_length(trim(content)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists post_comments_post_id_created_at_idx
  on public.post_comments(post_id, created_at);

create table if not exists public.post_reactions (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  voter_id uuid not null,
  reaction text not null check (reaction in ('like','dislike')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(post_id, voter_id)
);

create index if not exists post_reactions_post_id_idx on public.post_reactions(post_id);

alter table public.post_comments enable row level security;
alter table public.post_reactions enable row level security;

drop policy if exists "Public can read comments" on public.post_comments;
create policy "Public can read comments" on public.post_comments for select to anon, authenticated using (true);
drop policy if exists "Public can add comments" on public.post_comments;
create policy "Public can add comments" on public.post_comments for insert to anon, authenticated with check (true);
drop policy if exists "Authenticated admins can delete comments" on public.post_comments;
create policy "Authenticated admins can delete comments" on public.post_comments for delete to authenticated using (true);

drop policy if exists "Public can read reactions" on public.post_reactions;
create policy "Public can read reactions" on public.post_reactions for select to anon, authenticated using (true);
drop policy if exists "Public can add reactions" on public.post_reactions;
create policy "Public can add reactions" on public.post_reactions for insert to anon, authenticated with check (true);
drop policy if exists "Public can change reactions" on public.post_reactions;
create policy "Public can change reactions" on public.post_reactions for update to anon, authenticated using (true) with check (reaction in ('like','dislike'));

grant select, insert on public.post_comments to anon, authenticated;
grant delete on public.post_comments to authenticated;
grant select, insert, update on public.post_reactions to anon, authenticated;
