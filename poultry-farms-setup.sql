-- جدول فهرست مرغداری‌های دامیار
create table if not exists public.poultry_farms (
  id bigint generated by default as identity primary key,
  name text not null,
  city text,
  phone text,
  address text,
  description text,
  website_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.poultry_farms enable row level security;

drop policy if exists "Public reads active poultry farms" on public.poultry_farms;
create policy "Public reads active poultry farms"
on public.poultry_farms for select
to anon, authenticated
using (is_active = true);

drop policy if exists "Authenticated manages poultry farms" on public.poultry_farms;
create policy "Authenticated manages poultry farms"
on public.poultry_farms for all
to authenticated
using (true)
with check (true);

grant select on public.poultry_farms to anon, authenticated;
grant insert, update, delete on public.poultry_farms to authenticated;
grant usage, select on sequence public.poultry_farms_id_seq to authenticated;
